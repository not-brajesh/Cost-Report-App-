export const getMaterialsByCategory = () => {
  const byCategory = {};
  Object.entries(materialsDatabase).forEach(([name, data]) => {
    const cat = data.category || 'Other';
    if (!byCategory[cat]) byCategory[cat] = [];
    byCategory[cat].push({ name, ...data });
  });
  return byCategory;
};

